export const inlineParameters = (
  sql: string,
  parameters: readonly unknown[],
  dialect: Dialect
): string => {
  let next = 0
  return sql.replaceAll(
    /"(?:[^"]|"")*"|`(?:[^`]|``)*`|\[(?:[^\]]|\]\])*\]|'(?:[^']|'')*'|[$@:](?<index>\d+)|\?/gu,
    (token, ...args) => {
      if (!/^[$@:?]/u.test(token)) {
        return token
      }
      const index = args.at(-1)?.index
      next += 1
      return formatValue(
        parameters[index ? Number(index) - 1 : next - 1],
        dialect
      )
    }
  )
}

const IDENTITY_SPELLING: Record<Dialect, string | null> = {
  clickhouse: null,
  mongodb: null,
  mssql: 'IDENTITY(1,1)',
  mysql: 'AUTO_INCREMENT',
  oracle: 'GENERATED BY DEFAULT AS IDENTITY',
  postgres: 'GENERATED BY DEFAULT AS IDENTITY',
  sqlite: null,
}

const qualify = (schema: string, table: string, dialect: Dialect) =>
  `${quoteIdentifier(schema, dialect)}.${quoteIdentifier(table, dialect)}`

export const generateQuerySQL = ({
  table,
  schema,
  filters,
  dialect,
}: QueryParams) => {
  if (!isSqlDialect(dialect)) {
    return unsupported('SQL code')()
  }
  const db = coldDialect(dialect)
  const base = db
    .withSchema(schema)
    .$extendTables<{ [table]: Record<string, unknown> }>()
    .selectFrom(table)
    .selectAll()
  const query =
    filters.length > 0 ? base.where((eb) => toKyselyFilter(eb, filters)) : base
  const compiled = query.compile()
  return formatSql(
    inlineParameters(compiled.sql, compiled.parameters, dialect),
    dialect
  )
}

const SERIAL_BY_INT_TYPE: Record<string, string> = {
  BIGINT: 'BIGSERIAL',
  INTEGER: 'SERIAL',
  SMALLINT: 'SMALLSERIAL',
}

const formatEnumType = (
  c: Column,
  enumName: string,
  values: string[],
  dialect: Dialect
) => {
  if (dialect === Dialect.MySQL) {
    const valuesList = values.map((v) => formatValue(v, dialect)).join(', ')
    return `${c.type === 'set' ? 'SET' : 'ENUM'}(${valuesList})`
  }
  if (dialect === Dialect.MSSQL) {
    return enumName
  }
  return `${quoteIdentifier(enumName, dialect)}${c.isArray ? '[]' : ''}`
}

const formatScalarType = (c: Column, dialect: Dialect) => {
  let typeDef =
    dialect === Dialect.ClickHouse ? c.type : (c.typeLabel ?? c.type)
  if (!typeDef) {
    throw new Error(`Missing type for column ${c.id}`)
  }
  if (dialect === Dialect.ClickHouse) {
    return typeDef
  }
  if (dialect !== Dialect.Postgres && c.declaredType) {
    return c.declaredType.replace(/^[^']*/u, (head) => head.toUpperCase())
  }

  if (typeof c.maxLength === 'number') {
    const len = c.maxLength === -1 ? 'MAX' : c.maxLength
    if (/(?:var)?char|binary/iu.test(typeDef) && !/text/iu.test(typeDef)) {
      typeDef += `(${len})`
    }
  }

  if (typeof c.precision === 'number' && /decimal|numeric/iu.test(typeDef)) {
    typeDef += `(${c.precision}${c.scale ? `, ${c.scale}` : ''})`
  }

  return typeDef.toUpperCase()
}

const getTypeDef = (
  c: Column,
  dialect: Dialect,
  usedEnums: Map<string, string[]>
): string => {
  if (
    dialect !== Dialect.ClickHouse &&
    c.enumName &&
    c.availableValues?.length
  ) {
    if (dialect === Dialect.Postgres) {
      usedEnums.set(c.enumName, c.availableValues)
    }
    return formatEnumType(c, c.enumName, c.availableValues, dialect)
  }

  return formatScalarType(c, dialect)
}

const buildColumnParts = (
  c: Column,
  typeDef: string,
  dialect: Dialect,
  pkColumns: string[],
  unique: boolean,
  defaultValue?: string | null
): { parts: string[]; foreignKey: string | null } => {
  const quoted = quoteIdentifier(c.id, dialect)
  const parts = [quoted, typeDef]

  if (c.primaryKey) {
    pkColumns.push(quoted)
  }

  const identity = IDENTITY_SPELLING[dialect]
  if (c.isIdentity && identity) {
    parts.push(identity)
  }

  if (!c.isIdentity && defaultValue !== undefined && defaultValue !== null) {
    parts.push(`DEFAULT ${defaultValue}`)
  }

  if (!c.isNullable) {
    parts.push('NOT NULL')
  }

  if (unique && !c.primaryKey && dialect !== Dialect.ClickHouse) {
    parts.push('UNIQUE')
  }

  const foreignKey =
    c.foreign && dialect !== Dialect.ClickHouse
      ? `  FOREIGN KEY (${quoted}) REFERENCES ${qualify(c.foreign.schema, c.foreign.table, dialect)}(${quoteIdentifier(c.foreign.column, dialect)})${referentialActionClauses(c.foreign)}`
      : null

  return { foreignKey, parts }
}

const indexStatement = (
  idx: ReturnType<typeof explicitIndexes>[number],
  schema: string,
  qualifiedTable: string,
  dialect: Dialect
) =>
  idx.custom && idx.definition
    ? idx.definition
    : [
        'CREATE',
        idx.isUnique ? 'UNIQUE' : '',
        'INDEX',
        // An unqualified Oracle index lands in the session's schema, not the table's.
        dialect === Dialect.Oracle
          ? qualify(schema, idx.name, dialect)
          : quoteIdentifier(idx.name, dialect),
        'ON',
        qualifiedTable,
        dialect === Dialect.Postgres && idx.type ? `USING ${idx.type}` : '',
        `(${idx.keys
          .map((key) =>
            'column' in key
              ? quoteIdentifier(key.column, dialect)
              : key.expression
          )
          .join(', ')})`,
      ]
        .filter(Boolean)
        .join(' ')

export const generateSchemaSQL = ({
  table,
  schema,
  columns,
  dialect,
  indexes,
}: SchemaParams) => {
  const usedEnums = new Map<string, string[]>()
  const pkColumns: string[] = []
  const columnLines: string[] = []
  const foreignKeys: string[] = []

  for (const c of columns) {
    let typeDef = getTypeDef(c, dialect, usedEnums)
    let { defaultValue } = c

    if (dialect === Dialect.Postgres && isSerialDefault(defaultValue)) {
      const serialType = SERIAL_BY_INT_TYPE[typeDef]
      if (serialType) {
        typeDef = serialType
        defaultValue = null
      }
    }

    const { parts, foreignKey } = buildColumnParts(
      c,
      typeDef,
      dialect,
      pkColumns,
      isSingleColumnConstraint(c, columns, 'unique'),
      defaultValue
    )
    columnLines.push(`  ${parts.join(' ')}`)
    if (foreignKey) {
      foreignKeys.push(foreignKey)
    }
  }

  const primaryKey =
    pkColumns.length > 0 && dialect !== Dialect.ClickHouse
      ? [`  PRIMARY KEY (${pkColumns.join(', ')})`]
      : []
  const qualifiedTable = qualify(schema, table, dialect)
  const createTable = `CREATE TABLE ${qualifiedTable} (\n${[...columnLines, ...primaryKey, ...foreignKeys].join(',\n')}\n)`

  if (dialect === Dialect.ClickHouse) {
    const orderBy =
      pkColumns.length > 0 ? `(${pkColumns.join(', ')})` : 'tuple()'
    return `${createTable} ENGINE = MergeTree() ORDER BY ${orderBy};`
  }

  const enumStatements = Array.from(
    usedEnums,
    ([name, values]) =>
      `CREATE TYPE ${quoteIdentifier(name, dialect)} AS ENUM (${values.map((v) => formatValue(v, dialect)).join(', ')});`
  )
  const indexStatements = explicitIndexes({
    columns,
    indexes,
    schema,
    table,
  }).map((idx) => `${indexStatement(idx, schema, qualifiedTable, dialect)};`)

  return [
    enumStatements.join('\n'),
    `${createTable};`,
    indexStatements.join('\n'),
  ]
    .filter(Boolean)
    .join('\n\n')
}
